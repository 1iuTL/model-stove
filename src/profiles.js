// 任务档位定义。
//
// 为什么需要档位:同一套采样参数不可能同时适合推理和创作。
//
// ⚠️ 这里曾经写着"推理档写小说输出为空 —— 思考把整个 token 预算吃光了",
// 并把它当成档位的固有缺陷。**那个结论是错的,至少是过度概括。**
// 复测(2026-09,同一道几何题、同一模型、官方 prism 构建):
//
//   max_tokens=2048 + 开思考 -> reasoning 434 字符 + content 389 字符  正常
//   max_tokens=256  + 开思考 -> reasoning 348 字符 + content 108 字符  仍可用
//
// 也就是说:思考**不会**必然吃光预算,它只是先花掉一部分。当初得到"输出为空"
// 有两个叠加原因,都不是档位本身的问题:
//   1. 当时测试的 max_tokens 很小(600 量级),思考写完就没余量了
//   2. 当时**用错了 llama.cpp 构建**(社区 fast fork 跑三值模型会塌缩成连续
//      斜杠)—— 那才是真凶,详见 src/config.js 里 fork 配对的说明
//
// 现在的做法不是靠"默认关掉思考"来规避,而是给用户一个**随时可切的入口**
// (代理会往 Web UI 注入一个档位面板,见 ui-inject.mjs),用错档的成本从
// "这轮废了"降到"点一下重来"。
//
// 实测(解题速度):推理档最快,思考内容不长且直接给答案;其它三档回答更长。
// 所以档位的意义是"按任务选",不是"某档有毛病"。
//
// 关键约束:llama.cpp 的 Web UI 会在**请求里**自带采样参数,而请求级优先于
// 服务端启动参数(实测:请求里 t=0.01 时三次输出完全相同,证明请求确实生效)。
// 因此档位必须在**请求层**覆盖 —— 只改命令行不起作用。
module.exports = {
  profiles: [
    {
      key: 'chat',
      label: '通用',
      hint: '日常问答与创作,平衡取向',
      // 实测:创作任务里这个档写得最长(889 字),数学题也答对
      params: {
        temperature: 0.8,
        top_p: 0.95,
        top_k: 30,
        repeat_penalty: 1.08,
        presence_penalty: 0.2,
      },
      thinking: false,
    },
    {
      key: 'reason',
      label: '推理',
      hint: '数学与逻辑,开思考、低温度',
      params: {
        temperature: 0.7,
        top_p: 0.95,
        top_k: 20,
      },
      thinking: true,
    },
    {
      key: 'write',
      label: '写作',
      hint: '长文与创意,高温度 + 重复惩罚',
      params: {
        temperature: 1.05,
        top_p: 0.95,
        top_k: 40,
        repeat_penalty: 1.12,
        presence_penalty: 0.3,
      },
      thinking: false,
    },
    {
      key: 'code',
      label: '代码',
      hint: '写代码与排错,关思考、低温度',
      params: {
        temperature: 0.5,
        top_p: 0.95,
        top_k: 20,
      },
      thinking: false,
      // ⚠️ 2026-09-30 实测结论:**默认不采用**提示词约束。机制与本轮数据留在这里备查。
      //
      // 现象:三个模型都会在产物结束后追加说明(qwen36 还多带一个 markdown 表格),
      //   保存成 .html 时这些内容会混进去。注意**不是标签没闭合** —— </html> 与
      //   </body> 三个产物都齐,问题纯粹是"多出来的尾巴"。
      //
      // 两轮实测(同一提示词、同一配置 ncm23/t12,每档各一次):
      //   无约束            → 总长 15.6k/16.5k,</html> 后 413/435 字,@keyframes 14
      //   约束版一("…立即停止") → 总长  3.8k,</html> 后   0 字 ✓,但 @keyframes  0
      //   约束版二("…要完整")   → 总长  4.2k,</html> 后   0 字 ✓,同样瘦
      //   两版产物都**仍是可用动画**(车轮辐条旋转 + 车身 + 整体起伏),只是没了装饰。
      //
      // 关键:**去掉"立即停止"并显式要求完整性,并没有把丰富度找回来** ——
      //   所以这不是措辞问题,而是"只要加了输出纪律,模型就切到精简模式"。
      //
      // 取舍(为什么不默认开):一句尾巴是**可忽略**的,Web UI 的代码块复制按钮
      //   本来就只复制围栏内的内容;而缩水的产物是**真实的质量损失**。
      //   如果哪天想要干净的尾巴,再启用下面这行,并接受产物变精简:
      // systemAdd: '输出纪律:直接输出被要求的产物本身,不要输出开场白、说明、总结或结尾寒暄。',
    },
  ],
  defaultProfile: 'chat',

  /** 按 key 取档位;找不到就回落到默认档。 */
  resolve(key) {
    const list = module.exports.profiles
    return list.find((p) => p.key === key) || list.find((p) => p.key === module.exports.defaultProfile) || list[0]
  },
};
